#!/usr/bin/env python3
"""Prepare the aerial photos for the repository: strip metadata, downscale, contact sheet.

Non-destructive: the originals in source/photos/ are never touched, everything written goes
to source/photos/web/. This is the step that keeps location data out of the public repo —
drone photos carry GPS, and `exiftool` is not installed here, so Pillow is enough:
re-encoding without an EXIF block drops camera data and coordinates together.

usage: python scripts/photos.py [--max-side 2048] [--sheet]
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps

SRC = Path(__file__).resolve().parent.parent / "source" / "photos"
WEB = SRC / "web"
EXTS = {".jpg", ".jpeg", ".png", ".tif", ".tiff"}


def describe(path: Path) -> dict:
    with Image.open(path) as img:
        exif = img.getexif()
        gps = {}
        try:
            gps = dict(img.getexif().get_ifd(0x8825))
        except Exception:
            pass
        return {"frames": getattr(img, "n_frames", 1), "size": list(img.size),
                "make": exif.get(271), "model": exif.get(272), "has_gps": bool(gps),
                "mpo": path.suffix.lower() in {".jpg", ".jpeg"} and getattr(img, "n_frames", 1) > 1}


def process(path: Path, max_side: int) -> dict:
    info = describe(path)
    with Image.open(path) as img:
        img = ImageOps.exif_transpose(img)            # respect the orientation tag, then drop it
        img = img.convert("RGB")
        w, h = img.size
        if max(w, h) > max_side:
            scale = max_side / max(w, h)
            img = img.resize((round(w * scale), round(h * scale)), Image.LANCZOS)
        out = WEB / (path.stem + ".jpg")
        # Pillow writes no EXIF/GPS unless explicitly asked for, so re-encoding strips them
        img.save(out, "JPEG", quality=88, optimize=True, progressive=True)
        # re-save without any metadata (Pillow writes no EXIF unless asked)
        data = out.read_bytes()
        return {"source": path.name, "source_bytes": path.stat().st_size,
                "source_size": info["size"], "frames": info["frames"],
                "camera": " ".join(str(x) for x in (info["make"], info["model"]) if x),
                "gps_in_original": info["has_gps"],
                "out": f"web/{out.name}", "out_bytes": out.stat().st_size,
                "out_size": list(img.size),
                "sha1_12": hashlib.sha1(data).hexdigest()[:12]}


def contact_sheet(rows: list[dict], cols: int = 4, thumb_w: int = 480) -> Path:
    cell_h = int(thumb_w * 9 / 16) + 22
    rows_n = (len(rows) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * thumb_w, rows_n * cell_h), (12, 12, 12))
    draw = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.load_default(16)
    except TypeError:                                   # older Pillow signature
        font = ImageFont.load_default()
    for i, row in enumerate(rows):
        path = WEB / Path(row["out"]).name
        with Image.open(path) as img:
            img.thumbnail((thumb_w, int(thumb_w * 9 / 16)), Image.LANCZOS)
            x, y = (i % cols) * thumb_w, (i // cols) * cell_h
            sheet.paste(img, (x + (thumb_w - img.width) // 2, y))
            draw.text((x + 6, y + int(thumb_w * 9 / 16) + 4), row["source"], fill=(230, 230, 230), font=font)
    out = WEB / "contact_sheet.jpg"
    sheet.save(out, "JPEG", quality=86, optimize=True)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--max-side", type=int, default=2048)
    ap.add_argument("--no-sheet", action="store_true")
    args = ap.parse_args()

    photos = sorted(p for p in SRC.iterdir() if p.suffix.lower() in EXTS and p.is_file())
    if not photos:
        raise SystemExit(f"no photos in {SRC}")
    WEB.mkdir(exist_ok=True)
    rows = [process(p, args.max_side) for p in photos]

    total_in = sum(r["source_bytes"] for r in rows)
    total_out = sum(r["out_bytes"] for r in rows)
    print(f"{'source':<16} {'original':>14} {'web':>13} {'gps':>5} {'fr':>3}  camera")
    for r in rows:
        print(f"{r['source']:<16} {r['source_size'][0]}x{r['source_size'][1]} "
              f"{r['source_bytes']/2**20:6.1f}MB -> {r['out_size'][0]}x{r['out_size'][1]} "
              f"{r['out_bytes']/2**20:5.2f}MB {'yes' if r['gps_in_original'] else 'no ':>4} "
              f"{r['frames']:>2}  {r['camera']}")
    print(f"total: {total_in/2**20:.1f} MB -> {total_out/2**20:.1f} MB in {len(rows)} files")

    manifest = ["# Prepared copies (generated by scripts/photos.py)", "",
                "Metadata (camera, GPS) is stripped by re-encoding; originals in the parent",
                "directory keep theirs and are the working files for ComfyUI.", "",
                "| file | from | to | bytes | GPS in original | sha1 |", "|---|---|---|---|---|---|"]
    manifest += [f"| {r['out']} | {r['source_size'][0]}x{r['source_size'][1]} | "
                 f"{r['out_size'][0]}x{r['out_size'][1]} | {r['out_bytes']/2**20:.2f} MB | "
                 f"{'yes' if r['gps_in_original'] else 'no'} | `{r['sha1_12']}` |" for r in rows]
    (WEB / "MANIFEST.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print(f"wrote web/MANIFEST.md ({len(rows)} entries)")
    if not args.no_sheet:
        sheet = contact_sheet(rows)
        print(f"wrote {sheet.name} ({sheet.stat().st_size/2**20:.2f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
